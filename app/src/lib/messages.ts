export function translateMessage(
  text: string,
  locale: "es" | "en" | "fr",
  dictionary: Record<string, { en: string; fr: string }> = messages
): string {
  if (locale === "es" || !Object.hasOwn(dictionary, text)) return text;
  return dictionary[text][locale];
}
